#define GLYPH_COUNT (int) (sizeof(GLYPHS) / sizeof(GLYPHS[0]))

bool font_get_glyph(char c, u8 rows[FONT_GLYPH_HEIGHT]) {
    int i = 0;
    while (i < GLYPH_COUNT) {
        if (GLYPHS[i].c == c) {
            int row = 0;
            while (row < FONT_GLYPH_HEIGHT) {
                rows[row] = GLYPHS[i].rows[row];
                row = row + 1;
            }
            return true;
        }
        i = i + 1;
    }
    return false;
}
